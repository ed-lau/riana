"""Generate ``reference.qmd``, the CLI reference page, from the Typer app itself.

The page lists every command's arguments and options (names, values, defaults, help)
exactly as ``riana <command> --help`` defines them, so it cannot drift from the code.
``tests/test_docs.py`` fails when the committed page is out of date; regenerate with::

    python riana_website/_gen_reference.py

(Quarto ignores files starting with ``_``, so this script is not rendered.)
"""

from __future__ import annotations

import re
import sys
from pathlib import Path

PAGE = Path(__file__).with_name("reference.qmd")

HEADER = """\
---
title: "CLI Reference"
format: html
description: "Every riana command, argument and option, generated from the command-line interface."
---

<!-- Generated by riana_website/_gen_reference.py from the riana CLI. Do not edit by hand:
     change the help text in riana/cli.py and rerun the script. -->

Every command, argument and option of the `riana` command line, generated from the CLI
itself (`riana <command> --help` prints the same text). List options such as `--iso` take
a single comma/space-separated value. The desktop app (`riana gui`) builds the same
settings from its forms.
"""


def _text(s: str | None) -> str:
    """Help text as Markdown: RST ``code`` → `code`, and HTML-significant ``<``/``>``
    escaped outside code spans (``<run>_riana.txt`` would otherwise vanish)."""
    if not s:
        return ""
    s = re.sub(r"``(.+?)``", r"`\1`", s).replace("\\[", "[")   # Rich-escaped [ → [
    parts = re.split(r"(`[^`]*`)", s)
    return "".join(p if p.startswith("`") else p.replace("<", "&lt;").replace(">", "&gt;")
                   for p in parts)


def _cell(s: str) -> str:
    """One Markdown table cell: single line, pipes escaped outside code spans (a code
    span keeps its ``|`` in a pipe table, and would show an escaping backslash)."""
    parts = re.split(r"(`[^`]*`)", " ".join(_text(s).split()))
    return "".join(p if p.startswith("`") else p.replace("|", "\\|") for p in parts)


def _paragraphs(s: str | None) -> str:
    """A docstring as Markdown paragraphs (reflowed; blank lines kept)."""
    blocks = [" ".join(b.split()) for b in (s or "").strip().split("\n\n")]
    return "\n\n".join(_text(b) for b in blocks if b)


# The page is built from the *declarations* in riana/cli.py — each parameter's
# typer.Option(...) / typer.Argument(...) object and its type hint — rather than from
# the click objects Typer builds from them. The declarations are Typer's public API;
# the built objects' internals change between Typer releases (0.29 dropped `.type`).

def _unwrap(hint):
    """``(base type, is_list)`` from a type hint: strips ``Optional``, notes ``List``."""
    import typing

    args = [a for a in typing.get_args(hint) if a is not type(None)]
    origin = typing.get_origin(hint)
    if origin is typing.Union and len(args) == 1:
        return _unwrap(args[0])
    if origin in (list, typing.List):
        return (args[0] if args else str), True
    return hint, False


def _value(info, hint) -> str:
    base, many = _unwrap(hint)
    if base is bool:
        return "flag"
    if info.metavar:
        name = info.metavar
    elif base is int:
        name = "INTEGER"
    elif base is float:
        name = "FLOAT"
    elif base is Path:
        file_ok, dir_ok = getattr(info, "file_okay", True), getattr(info, "dir_okay", True)
        name = "FILE" if file_ok and not dir_ok else "DIRECTORY" if dir_ok and not file_ok else "PATH"
    else:
        name = "TEXT"
    return f"`{name.upper()}{' …' if many else ''}`"


def _required(info) -> bool:
    return info.default is ...


def _default(info, hint) -> str:
    if _required(info):
        return "required"
    d = info.default
    if _unwrap(hint)[0] is bool:
        return "on" if d else "off"
    if d is None or d == () or d == []:
        return "–"
    if isinstance(d, (list, tuple)):
        d = " ".join(map(str, d))
    return f"`{d}`"


def _names(info, pname: str) -> str:
    decls = [n for d in (info.param_decls or ()) for n in d.split("/")] \
        or ["--" + pname.replace("_", "-")]
    return ", ".join(f"`{n}`" for n in decls)


def _params(callback):
    """``[(name, info, hint, is_argument)]`` in signature order (hidden ones dropped)."""
    import inspect
    import typing

    import typer.models as tm

    hints = typing.get_type_hints(callback)
    out = []
    for name, p in inspect.signature(callback).parameters.items():
        info = p.default
        if isinstance(info, (tm.ArgumentInfo, tm.OptionInfo)) and not info.hidden:
            out.append((name, info, hints.get(name, str), isinstance(info, tm.ArgumentInfo)))
    return out


def _usage(name: str, params) -> str:
    pieces = [f"riana {name}", "[OPTIONS]"]
    for pname, info, hint, is_arg in params:
        if is_arg:
            arg = pname.upper() + (" ..." if _unwrap(hint)[1] else "")
            pieces.append(arg if _required(info) else f"[{arg}]")
    return " ".join(pieces)


def _command(name: str, callback, help_text: str | None) -> str:
    import inspect

    params = _params(callback)
    out = [f"## `riana {name}`", "", _paragraphs(help_text or inspect.getdoc(callback)),
           "", "```", _usage(name, params), "```", ""]
    args = [p for p in params if p[3]]
    if args:
        out += ["### Arguments", "", "| Argument | Value | Description |", "|---|---|---|"]
        out += [f"| `{n.upper()}` | {_value(i, h)} | {_cell(i.help or '')} |"
                for n, i, h, _ in args]
        out.append("")
    panels: dict[str, list] = {}
    for p in params:
        if not p[3]:
            panels.setdefault(p[1].rich_help_panel or "Options", []).append(p)
    for panel, rows in panels.items():
        out += [f"### {panel}", "", "| Option | Value | Default | Description |",
                "|---|---|---|---|"]
        out += [f"| {_names(i, n)} | {_value(i, h)} | {_default(i, h)} | {_cell(i.help or '')} |"
                for n, i, h, _ in rows]
        out.append("")
    return "\n".join(out)


def build_reference() -> str:
    """The full page text."""
    from riana.cli import app

    sections = [
        _command(ci.name or ci.callback.__name__.replace("_", "-"), ci.callback, ci.help)
        for ci in app.registered_commands
    ]
    return HEADER + "\n" + "\n".join(sections).rstrip() + "\n"


def main() -> int:
    PAGE.write_text(build_reference())
    print(f"wrote {PAGE}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
